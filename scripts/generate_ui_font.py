"""生成菜单中文字库；常规编译直接使用已提交的 C 文件。

使用 LVGL 自带 Source Han Sans（SIL OFL）及固定版本 lv_font_conv。
需要 Node.js/npx。字形仅包含 UI 文本和 ASCII，SSID 的常见中文由备用字库补足。
"""
from pathlib import Path
import argparse
import re
import shutil
import subprocess
import tempfile


def main():
    root = Path(__file__).resolve().parents[1]
    source = (root / "main/ui_service.c").read_text(encoding="utf-8")
    strings = re.findall(r'"([^"\n]*)"', source)
    symbols = "".join(sorted({c for s in strings for c in s if ord(c) > 127}))
    parser = argparse.ArgumentParser()
    parser.add_argument("--font-dir", type=Path, default=root / "managed_components/lvgl__lvgl/scripts/built_in_font")
    font_dir = parser.parse_args().font_dir
    npx = shutil.which("npx.cmd") or shutil.which("npx")
    if not npx:
        raise SystemExit("需要 Node.js/npx")
    with tempfile.TemporaryDirectory(prefix="vocat-font-") as temp:
        output = Path(temp) / "vocat_ui_font_20.c"
        subprocess.run([
            npx, "--yes", "lv_font_conv@1.5.3", "--font",
            str(font_dir / "SourceHanSansSC-Normal.otf"), "--size", "20", "--bpp", "4",
            "--format", "lvgl", "--no-compress", "--no-kerning", "--range", "0x20-0x7e",
            "--symbols", symbols, "--output", str(output),
        ], check=True)
        data = re.sub(r" \* Opts:.*", " * Generated by scripts/generate_ui_font.py",
                      output.read_text(encoding="utf-8"))
        # ESP-IDF 组件导出 lvgl.h，目录名为 lvgl__lvgl，不能依赖 lvgl/lvgl.h。
        data = re.sub(r'#ifdef LV_LVGL_H_INCLUDE_SIMPLE.*?#endif', '#include "lvgl.h"', data, count=1, flags=re.S)
        (root / "main/vocat_ui_font_20.c").write_text(data, encoding="utf-8", newline="\n")
    shutil.copyfile(font_dir / "font_license/SourceHanSansSC/LICENSE.txt",
                    root / "main/vocat_ui_font_LICENSE.txt")
    print(f"Generated UI font: ASCII + {len(symbols)} CJK/punctuation glyphs")


if __name__ == "__main__":
    main()
